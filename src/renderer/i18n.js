function createI18n(initialLanguage = 'zh-CN') {
  let language = I18N[initialLanguage] ? initialLanguage : 'zh-CN';

  function t(key, params = {}) {
    const template = I18N[language][key] || I18N['zh-CN'][key] || key;
    return template.replace(/\{(\w+)\}/g, (_match, name) => {
      return Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : `{${name}}`;
    });
  }

  return {
    getLanguage: () => language,
    setLanguage: (nextLanguage) => {
      language = I18N[nextLanguage] ? nextLanguage : 'zh-CN';
      return language;
    },
    t,
  };
}

